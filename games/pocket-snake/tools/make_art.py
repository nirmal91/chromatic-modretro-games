CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789:/-+!.?<>"

TILES = [
    ['........'] * 8,
    ['33333333','32222223','32111123','32111123','32111123','32111123','32222223','33333333'],
    ['........','.333333.','.322223.','.321123.','.321123.','.322223.','.333333.','........'],
    ['...33...','..3223..','.321123.','.322223.','.322223.','.321123.','..3333..','........'],
    ['........','.333333.','.322223.','.323323.','.322223.','.323323.','.333333.','........'],
]
def encode(rows):
    data=[]
    for row in rows:
        pixels=[int(c) if c!='.' else 0 for c in row]
        data += [sum((p&1)<<(7-i) for i,p in enumerate(pixels)), sum(((p>>1)&1)<<(7-i) for i,p in enumerate(pixels))]
    return data
for ch in CHARS:
    TILES.append(['........'] + ['.' + ''.join('3' if int(h,16)&(1<<(4-i)) else '.' for i in range(5)) + '..' for h in GLYPHS[ch]])
