def encode(rows):
    data = []
    for row in rows:
        pixels = [int(c) if c != "." else 0 for c in row]
        data.extend(
            [sum((p & 1) << (7 - i) for i, p in enumerate(pixels)),
             sum(((p >> 1) & 1) << (7 - i) for i, p in enumerate(pixels))]
        )
    return data


def fmt(data):
    return ",".join(f"0x{x:02x}" for x in data)


